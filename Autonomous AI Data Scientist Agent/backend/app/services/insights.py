"""AI insights & explainability: findings, partial dependence, per-row explanations and a Q&A engine.

Everything is computed from the real data / model results, nothing is generated by an external service.
"""
from __future__ import annotations

import re
from typing import Optional

import numpy as np
import pandas as pd
from fastapi import HTTPException


def _fmt_pct(x: float) -> str:
    return f"{100 * x:.1f}%"


# ----------------------------------------------------------------------------- partial dependence
def _response(bundle: dict, X: pd.DataFrame, cls_idx: Optional[int]) -> np.ndarray:
    pipe = bundle["pipeline"]
    if bundle["task"] == "classification":
        return pipe.predict_proba(X)[:, cls_idx]
    return pipe.predict(X)


def pdp_curves(bundle: dict, features: list[str], n_rows: int = 300, points: int = 12) -> list[dict]:
    X = bundle["X_train"]
    X = X.sample(min(len(X), n_rows), random_state=0).copy()
    cls_idx, cls_name = None, None
    if bundle["task"] == "classification":
        classes = bundle["classes"]
        if len(classes) == 2:
            cls_idx = 1
        else:
            cls_idx = int(np.argmax(bundle["pipeline"].predict_proba(X).mean(axis=0)))
        cls_name = classes[cls_idx]
    out = []
    for feat in features:
        if feat not in X.columns:
            continue
        if feat in bundle["num_cols"]:
            grid = np.unique(np.nanpercentile(X[feat].astype(float), np.linspace(5, 95, points)))
            if len(grid) < 2:
                continue
            ys = []
            for v in grid:
                Xm = X.copy()
                Xm[feat] = v
                ys.append(float(np.mean(_response(bundle, Xm, cls_idx))))
            corr = float(np.corrcoef(grid, ys)[0, 1]) if np.std(ys) > 0 else 0.0
            if abs(corr) < 0.4:
                direction = "has a weak or non-linear effect"
            elif corr > 0:
                direction = "pushes the prediction up as it increases"
            else:
                direction = "pushes the prediction down as it increases"
            out.append({"feature": feat, "type": "number", "target_class": cls_name, "x": [float(g) for g in grid],
                        "y": ys, "direction": direction, "range": float(max(ys) - min(ys))})
        else:
            cats = X[feat].astype(str).value_counts().head(6).index.tolist()
            ys = []
            for v in cats:
                Xm = X.copy()
                Xm[feat] = v
                ys.append(float(np.mean(_response(bundle, Xm, cls_idx))))
            hi, lo = cats[int(np.argmax(ys))], cats[int(np.argmin(ys))]
            out.append({"feature": feat, "type": "category", "target_class": cls_name, "x": cats, "y": ys,
                        "direction": f"is highest for '{hi}' and lowest for '{lo}'", "range": float(max(ys) - min(ys))})
    return out


# ----------------------------------------------------------------------------- per-row explanation
def explain_row(bundle: dict, row_id: int) -> dict:
    X_test = bundle["X_test"]
    if row_id not in set(int(i) for i in X_test.index):
        raise HTTPException(400, f"Row {row_id} is not in the test set. Pick a row from the predictions table.")
    row = X_test.loc[[row_id]]
    pipe, task = bundle["pipeline"], bundle["task"]
    if task == "classification":
        proba = pipe.predict_proba(row)[0]
        ci = int(np.argmax(proba))
        base = float(proba[ci])
        label = bundle["classes"][ci]

        def f(r):
            return float(pipe.predict_proba(r)[0][ci])
    else:
        base = float(pipe.predict(row)[0])
        label = None

        def f(r):
            return float(pipe.predict(r)[0])
    contribs = []
    for c in bundle["features"]:
        alt = row.copy()
        alt[c] = bundle["background"][c]
        contribs.append({"feature": c, "value": row.iloc[0][c], "typical": bundle["background"][c], "effect": base - f(alt)})
    contribs.sort(key=lambda d: -abs(d["effect"]))
    return {"row": row_id, "prediction": label if label is not None else base, "score": base, "task": task,
            "contributions": contribs[:8]}


# ----------------------------------------------------------------------------- findings
def build_findings(meta: dict, prep: Optional[dict], eda: Optional[dict], ml: Optional[dict]) -> dict:
    findings: list[dict] = []
    nxt: list[str] = []

    if prep:
        s = prep["summary"]
        findings.append({"level": "good", "title": "Data was cleaned",
                         "text": f"Completeness improved from {s['completeness_before']}% to {s['completeness_after']}%. "
                                 f"{s['cells_imputed']:,} missing cells were imputed with machine learning, "
                                 f"{s['cells_repaired']:,} outlier cells were repaired by the autoencoder pipeline and "
                                 f"{s['duplicates_removed']:,} duplicate rows were removed."})
    else:
        findings.append({"level": "warning", "title": "Preprocessing was skipped",
                         "text": "Results use the raw file. Run the Data Preprocessing step for cleaner, more reliable models."})

    headline = f"Dataset '{meta.get('filename', 'dataset')}' has {meta.get('rows', 0):,} rows and {meta.get('cols', 0)} columns."
    drivers = []
    if ml:
        m, task = ml["metrics"], ml["task"]
        top = ml["feature_importance"][:5]
        perm = {p["feature"]: p for p in ml.get("permutation_importance", [])}
        drivers = [{"feature": t["feature"], "importance": t["importance"],
                    "permutation": perm.get(t["feature"], {}).get("importance")} for t in top]
        if task == "classification":
            lift = m["accuracy"] - m["baseline_accuracy"]
            level = "good" if lift > 0.05 else "warning"
            findings.append({"level": level, "title": "Model performance",
                             "text": f"The Random Forest predicts '{ml['target']}' with {_fmt_pct(m['accuracy'])} accuracy and F1 {m['f1']:.2f} "
                                     f"on unseen data. Always predicting the most common class would score {_fmt_pct(m['baseline_accuracy'])}, "
                                     f"so the model adds {100 * lift:+.1f} percentage points."})
            gap = m["train_accuracy"] - m["accuracy"]
            weak = [p for p in ml.get("per_class", []) if p["support"] >= 5 and p["recall"] < 0.4]
            if weak:
                findings.append({"level": "warning", "title": "Weak classes",
                                 "text": "Recall is low for: " + ", ".join(f"'{w['class']}' ({_fmt_pct(w['recall'])})" for w in weak) +
                                         ". The model misses many real cases of these classes."})
                nxt.append("Collect more examples of the weak classes or use resampling to balance the target.")
            headline += f" The model predicts '{ml['target']}' with {_fmt_pct(m['accuracy'])} accuracy."
        else:
            lift = m["r2"] - m["baseline_r2"]
            level = "good" if m["r2"] > 0.5 else "warning"
            findings.append({"level": level, "title": "Model performance",
                             "text": f"The Random Forest explains {_fmt_pct(max(m['r2'], 0))} of the variation in '{ml['target']}' "
                                     f"(R² {m['r2']:.2f}, average error {m['mae']:.3g}, RMSE {m['rmse']:.3g}) on unseen data."})
            gap = m["train_r2"] - m["r2"]
            headline += f" The model explains {_fmt_pct(max(m['r2'], 0))} of '{ml['target']}'."
        if gap > 0.25:
            findings.append({"level": "warning", "title": "Possible overfitting",
                             "text": f"Training score is {gap:.2f} higher than the test score. The model memorises the training rows more than it generalises."})
            nxt.append("Turn on hyper-parameter tuning, limit tree depth, or add more data.")
        if top and top[0]["importance"] > 0.6:
            findings.append({"level": "warning", "title": "One feature dominates",
                             "text": f"'{top[0]['feature']}' carries {_fmt_pct(top[0]['importance'])} of the importance. Check that it is not a leak of the target."})
        if top:
            findings.append({"level": "info", "title": "Main drivers",
                             "text": "The strongest predictors are " + ", ".join(f"'{t['feature']}' ({_fmt_pct(t['importance'])})" for t in top[:3]) + "."})
        if ml["n_train"] + ml["n_test"] < 500:
            findings.append({"level": "warning", "title": "Small dataset",
                             "text": f"Only {ml['n_train'] + ml['n_test']} rows were used, so results can change a lot with new data."})
            nxt.append("Gather more rows to make the metrics more stable.")
        cv = ml.get("cv")
        if cv:
            findings.append({"level": "info", "title": "Cross-validation",
                             "text": f"{cv['folds']}-fold cross-validation on the training data gives {cv['mean']:.3f} ± {cv['std']:.3f} ({cv['metric']}), "
                                     "which shows how stable the model is."})
        if not ml.get("tuned"):
            nxt.append("Re-train with hyper-parameter tuning to squeeze out extra accuracy.")
    else:
        nxt.append("Train the Random Forest on the Machine Learning page to unlock model explanations.")

    if eda:
        for ins in eda.get("insights", [])[:4]:
            findings.append({"level": ins["level"], "title": "Data observation", "text": ins["text"]})
    nxt.append("Review the strongest features and ask whether they are available at prediction time in your real process.")
    return {"headline": headline, "findings": findings, "drivers": drivers, "next_steps": nxt}


# ----------------------------------------------------------------------------- Q&A engine
SUGGESTED = ["What are the most important features?", "How accurate is the model?", "Is the model overfitting?",
             "What was cleaned in my data?", "Which columns are correlated?", "How can I improve the model?",
             "Give me a summary"]


def _mentioned_column(q: str, columns: list[str]) -> Optional[str]:
    q = q.lower()
    best = None
    for c in columns:
        names = {c.lower(), c.lower().replace("_", " ")}
        if any(re.search(r"(?<![a-z0-9])" + re.escape(n) + r"(?![a-z0-9])", q) for n in names):
            if best is None or len(c) > len(best):
                best = c
    return best


def answer_question(question: str, ctx: dict) -> dict:
    q = (question or "").strip().lower()
    if not q:
        raise HTTPException(400, "Please type a question.")
    meta, prep, eda, ml, ins = ctx["meta"], ctx.get("prep"), ctx.get("eda"), ctx.get("ml"), ctx.get("insights")
    cols = [c["name"] for c in (eda["columns"] if eda else [])] or (ml["features"] if ml else [])
    need_ml = "That needs a trained model. Open the Machine Learning page and train the Random Forest first."

    col = _mentioned_column(q, cols + ([ml["target"]] if ml else []))
    if col:
        parts = []
        info = next((c for c in (eda["columns"] if eda else []) if c["name"] == col), None)
        if info:
            if info["kind"] == "numeric":
                parts.append(f"'{col}' is numeric: mean {info['mean']:.4g}, median {info['median']:.4g}, range {info['min']:.4g} to {info['max']:.4g}, "
                             f"{info['outliers_iqr']} IQR outliers, {info['missing']} missing values.")
            elif info["kind"] == "categorical":
                tv = ", ".join(f"{t['value']} ({t['count']})" for t in info["top_values"][:4])
                parts.append(f"'{col}' is categorical with {info['unique']} distinct values. Most common: {tv}.")
            else:
                parts.append(f"'{col}' is a date column from {info['min']} to {info['max']}.")
        if ml:
            fi = next((f for f in ml["feature_importance"] if f["feature"] == col), None)
            if fi:
                rank = [f["feature"] for f in ml["feature_importance"]].index(col) + 1
                parts.append(f"In the model it ranks #{rank} with {_fmt_pct(fi['importance'])} of the total importance.")
            elif col == ml["target"]:
                parts.append(f"It is the target the model predicts ({ml['task']}).")
            pdp = next((p for p in (ins or {}).get("pdp", []) if p["feature"] == col), None)
            if pdp:
                parts.append(f"Holding everything else constant, '{col}' {pdp['direction']}.")
        return {"answer": " ".join(parts) or f"I found column '{col}' but have no statistics for it yet.", "topic": "column"}

    def has(*words):
        return any(w in q for w in words)

    if has("important", "driver", "influenc", "matter", "top feature", "factor", "predictor", "feature"):
        if not ml:
            return {"answer": need_ml, "topic": "features"}
        top = ml["feature_importance"][:5]
        txt = "The most important features are: " + "; ".join(f"{i + 1}. {t['feature']} ({_fmt_pct(t['importance'])})" for i, t in enumerate(top)) + "."
        pdp = (ins or {}).get("pdp", [])[:3]
        if pdp:
            txt += " " + " ".join(f"'{p['feature']}' {p['direction']}." for p in pdp)
        return {"answer": txt, "topic": "features"}
    if has("overfit", "generali", "memoris", "memoriz"):
        if not ml:
            return {"answer": need_ml, "topic": "overfit"}
        m = ml["metrics"]
        if ml["task"] == "classification":
            gap, a, b = m["train_accuracy"] - m["accuracy"], m["train_accuracy"], m["accuracy"]
            name = "accuracy"
        else:
            gap, a, b = m["train_r2"] - m["r2"], m["train_r2"], m["r2"]
            name = "R²"
        verdict = "There are signs of overfitting." if gap > 0.25 else "Overfitting looks limited."
        return {"answer": f"{verdict} Training {name} is {a:.3f} and test {name} is {b:.3f} (gap {gap:.3f}). "
                          "Random Forests normally fit training data almost perfectly, so judge by the test score and the cross-validation result.", "topic": "overfit"}
    if has("accura", "perform", "metric", "how good", "score", "precision", "recall", "f1", "r2", "r²", "error", "auc", "reliable"):
        if not ml:
            return {"answer": need_ml, "topic": "performance"}
        m = ml["metrics"]
        if ml["task"] == "classification":
            txt = (f"On {ml['n_test']:,} unseen rows the model reaches accuracy {_fmt_pct(m['accuracy'])}, precision {m['precision']:.2f}, "
                   f"recall {m['recall']:.2f} and F1 {m['f1']:.2f}" + (f", ROC-AUC {m['roc_auc']:.2f}" if "roc_auc" in m else "") +
                   f". A model that always guesses the majority class would get {_fmt_pct(m['baseline_accuracy'])}.")
        else:
            txt = f"On {ml['n_test']:,} unseen rows: R² {m['r2']:.3f}, MAE {m['mae']:.4g}, RMSE {m['rmse']:.4g} (baseline R² {m['baseline_r2']:.3f})."
        if ml.get("cv"):
            txt += f" Cross-validation: {ml['cv']['mean']:.3f} ± {ml['cv']['std']:.3f}."
        return {"answer": txt, "topic": "performance"}
    if has("clean", "missing", "quality", "impute", "duplicate", "preprocess", "outlier", "autoencoder", "deep learning"):
        if not prep:
            return {"answer": "Preprocessing has not been run yet. Open the Data Preprocessing page and press Clean dataset.", "topic": "cleaning"}
        s = prep["summary"]
        steps = " ".join(f"• {st['title']}: {st['detail']}" for st in prep["steps"] if st["status"] == "done")
        return {"answer": f"Rows {s['rows_before']:,} → {s['rows_after']:,}, columns {s['cols_before']} → {s['cols_after']}, "
                          f"completeness {s['completeness_before']}% → {s['completeness_after']}%. {steps}", "topic": "cleaning"}
    if has("correlat", "relationship", "related"):
        if not eda or not eda.get("top_correlations"):
            return {"answer": "I need at least two numeric columns to talk about correlations.", "topic": "correlation"}
        tc = eda["top_correlations"][:4]
        return {"answer": "Strongest correlations: " + "; ".join(f"{t['a']} vs {t['b']} (r = {t['r']:.2f})" for t in tc) + ".", "topic": "correlation"}
    if has("improve", "better", "recommend", "next step", "suggest", "what should"):
        steps = (ins or {}).get("next_steps") or ["Train the model first."]
        return {"answer": "Suggested next steps: " + " ".join(f"{i + 1}) {s}" for i, s in enumerate(steps)), "topic": "recommendations"}
    if has("target", "label", "class", "distribution", "balance"):
        if eda and eda.get("target"):
            t = eda["target"]
            d = ", ".join(f"{x['value']} ({x['count']})" for x in t["distribution"][:6])
            return {"answer": f"The target '{t['name']}' is a {t['task']} problem. Distribution: {d}.", "topic": "target"}
        return {"answer": "Pick a target column on the Preprocessing or Machine Learning page first.", "topic": "target"}
    if has("how many", "rows", "columns", "size", "shape", "records", "dataset"):
        return {"answer": f"The dataset '{meta.get('filename')}' has {meta.get('rows', 0):,} rows and {meta.get('cols', 0)} columns" +
                          (f"; after cleaning it has {prep['summary']['rows_after']:,} rows and {prep['summary']['cols_after']} columns." if prep else "."), "topic": "size"}
    if has("model", "random forest", "train", "predict", "how does", "algorithm"):
        if not ml:
            return {"answer": need_ml, "topic": "model"}
        return {"answer": f"A Random Forest {'classifier' if ml['task'] == 'classification' else 'regressor'} with {ml['model_params']['n_estimators']} trees "
                          f"learned '{ml['target']}' from {len(ml['features'])} features using {ml['n_train']:,} rows and was tested on {ml['n_test']:,} unseen rows. "
                          "Each tree votes and the forest averages the votes.", "topic": "model"}
    if has("summar", "overview", "explain", "insight", "tell me", "result", "finding"):
        if ins:
            return {"answer": ins["headline"] + " " + " ".join(f["text"] for f in ins["findings"][:3]), "topic": "summary"}
    return {"answer": "I can answer questions about feature importance, model accuracy, overfitting, data cleaning, correlations, the target, "
                      "or any specific column (just mention its name). Try one of the suggestions below.", "topic": "help"}
